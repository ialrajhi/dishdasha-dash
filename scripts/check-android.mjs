import { _android, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
const sdk=process.env.ANDROID_HOME||process.env.ANDROID_SDK_ROOT||join(homedir(),'Library/Android/sdk');
const adb=join(sdk,'platform-tools',process.platform==='win32'?'adb.exe':'adb');
const serial=process.env.ANDROID_SERIAL||'emulator-5556';
const label=process.env.ANDROID_TEST_LABEL==='tablet'?'tablet':'phone';
const pkg='com.falrajhi.dishdashadash';
const run=(...args)=>execFileSync(adb,['-s',serial,...args],{encoding:'utf8'}).trim();
const delay=ms=>new Promise(r=>setTimeout(r,ms));
// WebView DevTools captures can omit its separate WebGL surface. Capture the composed device screen.
const screenshot=async name=>{await delay(350);await writeFile(`release/qa/${name}.png`,execFileSync(adb,['-s',serial,'exec-out','screencap','-p'],{maxBuffer:32*1024*1024}));};
async function connect() {
  const devices=await _android.devices();
  const device=devices.find(d=>d.serial()===serial);
  if(!device)throw Error('Android device not found');
  const webview=await device.webView({pkg});
  const page=await webview.page();
  return {browser:device,page};
}
await mkdir('release/qa',{recursive:true});
let {browser,page}=await connect();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await expect(page.locator('.game-title')).toBeVisible({timeout:30000});
await page.waitForSelector('.asset-loading',{state:'detached'});
await expect(page.locator('html')).toHaveAttribute('lang','en');
expect(await page.evaluate(()=>typeof window.__DASH__)).toBe('undefined');
if(label==='tablet') expect(await page.evaluate(()=>Math.min(innerWidth,innerHeight))).toBeGreaterThanOrEqual(600);
await screenshot(`android-${label}-menu`);
await page.locator('[data-action="options"]').click();
await page.locator('#volume').fill('30');
await page.locator('[data-action="reducedMotion"]').click();
await page.locator('[data-action="about"]').click();
await page.locator('[data-action="licenses"]').click();
await expect(page.locator('#license-copy')).toContainText('THIRD-PARTY NOTICES');
run('shell','input','keyevent','4');await expect(page.locator('.about-modal')).toContainText('Your privacy');
run('shell','input','keyevent','4');await expect(page.locator('.options-modal')).toBeVisible();
run('shell','input','keyevent','4');await expect(page.locator('.game-title')).toBeVisible();
await page.locator('[data-action="start"]').click();
await page.waitForTimeout(1600);
await expect(page.locator('#level-label')).toContainText('الفريج');
const bounds=await page.locator('#jump-button').boundingBox();
const density=await page.evaluate(()=>devicePixelRatio);
const x=String(Math.round((bounds.x+bounds.width/2)*density)),y=String(Math.round((bounds.y+bounds.height/2)*density));
run('shell','input','swipe',x,y,x,y,'180');
run('shell','input','keyevent','4');await expect(page.locator('.view-pause')).toBeVisible();
await screenshot(`android-${label}-paused`);
await page.locator('[data-action="resume"]').click();
run('shell','input','keyevent','3');await delay(400);
run('shell','am','start','-n',`${pkg}/.MainActivity`);await delay(500);
await expect(page.locator('.view-pause')).toBeVisible();
console.log('Android offline: menu, touch input, native Back, Home/return pause, Arabic HUD, and licenses passed.');
console.log('Native prefs',run('shell','run-as',pkg,'ls','shared_prefs'));
const before=await page.evaluate(()=>JSON.parse(localStorage.getItem('dishdasha-dash:v1')));
expect(before.settings.volume).toBe(30);
run('shell','am','force-stop',pkg);await browser.close();
run('shell','am','start','-n',`${pkg}/.MainActivity`);await delay(1000);
({browser,page}=await connect());
await page.waitForSelector('.asset-loading',{state:'detached'});
await page.locator('[data-action="options"]').click();
await expect(page.locator('#volume')).toHaveValue('30');
const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('dishdasha-dash:v1')));
expect(after.revision).toBeGreaterThanOrEqual(before.revision);
expect(after.settings.reducedMotion).toBe(before.settings.reducedMotion);
expect(errors).toEqual([]);
await writeFile(`release/qa/android-${label}-test.json`,JSON.stringify({testedAt:new Date().toISOString(),api:run('shell','getprop','ro.build.version.sdk'),abi:run('shell','getprop','ro.product.cpu.abi'),pageSize:run('shell','getconf','PAGE_SIZE'),viewport:await page.evaluate(()=>({width:innerWidth,height:innerHeight,dpr:devicePixelRatio})),wifi:run('shell','settings','get','global','wifi_on'),saveRestored:true,errors},null,2));
console.log('Android force-stop/relaunch restored native settings.');
await browser.close();
